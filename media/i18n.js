  function pick(lang) {
    lang = String(lang || "");
    if (STR[lang]) return lang;
    const l = lang.toLowerCase();
    if (STR["zh-Hant"] && /^zh[-_](tw|hk|mo|hant)/.test(l)) return "zh-Hant";
    if (STR[l.slice(0, 2)]) return l.slice(0, 2);
    return DEFAULT;
  }

